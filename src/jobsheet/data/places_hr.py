_CITY_SET = frozenset(CITIES)
_BY_FOLDED_COUNTY: dict[str, int] = {fold(name): number for number, name in COUNTIES.items()}


def county_feed_number(county: str) -> int | None:
    """The HZZ feed number for a county name, matched loosely.

    Loosely, because the name arrives from wherever the user found it: with or
    without the word "županija", with or without diacritics, in any case. All of
    those are one county to a person, so they are one county here.
    """
    wanted = fold(county).removesuffix("zupanija").strip()
    return _BY_FOLDED_COUNTY.get(wanted)


def _starts(name: str, wanted: str) -> bool:
    """Whether `name` begins with `wanted`, at the start of any of its words.

    Prefix rather than substring: somebody typing "rij" means Rijeka, not Marija
    Bistrica, and a list offering both is worse than the empty field it replaced.
    A later word still counts as a start, so "gorica" finds Velika Gorica.
    """
    folded = fold(name)
    if folded.startswith(wanted):
        return True
    return any(word.startswith(wanted) for word in folded.replace("-", " ").split())


def search_places(query: str, kind: str = "", limit: int = 20) -> list[dict[str, str]]:
    """Places whose name starts with `query`, best first.

    `kind` narrows the answer: "city" offers only the 128 cities, "county" only
    the 21 counties, anything else offers every place there is. An empty query is
    not an error -- it is what a field asks the moment it is focused, and the
    first twenty names are a better answer to that than nothing.
    """
    wanted = fold(query).strip()

    # Counties ignore the limit: there are twenty-one of them, the picker shows
    # them all the moment the field is focused, and a cap that could hide one
    # would be a bug rather than a feature.
    if kind == "county":
        return [
            {"name": name, "kind": "county", "county": name}
            for name in (COUNTIES[number] for number in sorted(COUNTIES))
            if not wanted or _starts(name, wanted)
        ]

    pool = CITIES if kind == "city" else PLACES
    hits = [name for name in pool if not wanted or _starts(name, wanted)]
    # A city before a municipality that starts the same way, then alphabetical:
    # the city is the one with ten times the vacancies.
    hits.sort(key=lambda name: (name not in _CITY_SET, fold(name)))
    return [
        {
            "name": name,
            "kind": "city" if name in _CITY_SET else "municipality",
            "county": COUNTY_OF.get(name, ""),
        }
        for name in hits[:limit]
    ]
